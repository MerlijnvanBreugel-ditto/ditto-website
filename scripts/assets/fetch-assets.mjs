// Download the Framer assets listed in manifest.json and write them to public/.
// Raster images become WebP at a width ladder; everything else is copied as-is.
// Also writes src/lib/images.gen.ts (widths + intrinsic size per image) for <Picture>.
// Usage (from scripts/): node assets/fetch-assets.mjs
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "../..");
const CACHE = path.join(ROOT, ".cache/framer");
const PUBLIC = path.join(ROOT, "public");
const LADDER = [320, 640, 1024, 1600, 2400, 3200];
const manifest = JSON.parse(fs.readFileSync(path.join(import.meta.dirname, "manifest.json"), "utf8"));

fs.mkdirSync(CACHE, { recursive: true });

async function download(entry) {
  const url = entry.url ?? `https://framerusercontent.com/${entry.src}`;
  const file = path.join(CACHE, path.basename(new URL(url).pathname));
  if (!fs.existsSync(file)) {
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    fs.writeFileSync(file, Buffer.from(await res.arrayBuffer()));
  }
  return file;
}

const out = {};
for (const img of manifest.images) {
  const file = await download(img);
  const meta = await sharp(file).metadata();
  const cap = Math.min(img.max, meta.width);
  const widths = [...LADDER.filter((w) => w < cap), cap];
  for (const w of widths) {
    const dest = path.join(PUBLIC, "assets", `${img.name}-${w}.webp`);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    await sharp(file)
      .resize({ width: w })
      .webp(img.lossless ? { lossless: true } : { quality: img.quality ?? 80 })
      .toFile(dest);
  }
  out[img.name] = { widths, width: meta.width, height: meta.height };
  console.log(img.name, meta.width, "x", meta.height, "->", widths.join(","));
}

for (const f of manifest.files) {
  const file = await download(f);
  const dest = path.join(PUBLIC, f.name);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.copyFileSync(file, dest);
  console.log(f.name);
}

const rows = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const ts = `// Generated by scripts/assets/fetch-assets.mjs. Do not edit by hand.
export const images = {
${rows.join("\n")}
} as const;

export type ImageName = keyof typeof images;
`;
fs.writeFileSync(path.join(ROOT, "src/lib/images.gen.ts"), ts);
